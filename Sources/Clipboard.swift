// Clipboard.swift. Watching the clipboard, pasting back, cleaning links, Markdown.
//
// Crash safety (common clipboard-manager issue: crashes on copy/paste in some apps): every read is optional,
// sizes are capped, nothing is force-unwrapped, and all work happens on the main thread.
import AppKit
import ApplicationServices

/// Marks clipboard content that Memo itself wrote, so it is never recorded twice.
let tenaxMarker = NSPasteboard.PasteboardType("com.solomon.tenax.own")

enum Privacy {
    /// nspasteboard.org markers: secrets, temporary and machine-made clipboard content.
    static let skipTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping",
        "Pasteboard generator type", "net.antelle.keeweb",
    ]
    /// Password managers, always skipped while "Skip passwords" is on.
    static let passwordApps: Set<String> = [
        "com.1password.1password", "com.agilebits.onepassword7", "com.agilebits.onepassword-osx",
        "com.bitwarden.desktop", "org.keepassxc.keepassxc", "com.apple.Passwords",
        "com.apple.keychainaccess", "com.dashlane.dashlanephonefinal", "com.lastpass.LastPass",
        "com.enpass.Enpass-Desktop", "in.sinew.Enpass-Desktop", "com.nordpass.macos.NordPass",
        "me.proton.pass.electron", "com.keepersecurity.passwordmanager", "net.antelle.keeweb",
    ]
}

final class ClipboardWatcher {
    var onNewClip: ((NewClip) -> Void)?
    var settings: () -> (paused: Bool, skipSecrets: Bool, cleanLinks: Bool, ignored: Set<String>) = { (false, true, true, []) }

    private var lastCount = NSPasteboard.general.changeCount
    private var timer: Timer?
    static let maxTextBytes = 1_000_000
    static let maxImageBytes = 30_000_000

    func start() {
        let t = Timer(timeInterval: 0.3, repeats: true) { [weak self] _ in self?.poll() }
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastCount else { return }
        lastCount = pb.changeCount
        let s = settings()
        if s.paused { return }
        let types = Set((pb.types ?? []).map(\.rawValue))
        if types.contains(tenaxMarker.rawValue) { return }
        let front = NSWorkspace.shared.frontmostApplication
        let bundle = front?.bundleIdentifier ?? ""
        if s.ignored.contains(bundle) { return }
        if s.skipSecrets {
            if !types.isDisjoint(with: Privacy.skipTypes) { Log.write("skipped secret clip"); return }
            if Privacy.passwordApps.contains(bundle) { Log.write("skipped password app"); return }
        }
        guard var clip = Self.read(pb, types: types) else { return }
        clip.source = front?.localizedName
        if clip.kind == .link, s.cleanLinks, let cleaned = LinkCleaner.clean(clip.text), cleaned != clip.text {
            clip.text = cleaned
            clip.cleaned = true
        }
        guard clip.kind == .image else { onNewClip?(clip); return }
        // Big pictures are converted off the main thread, so the menu bar never stalls.
        DispatchQueue.global(qos: .userInitiated).async { [weak self] in
            let ready = Self.prepareImage(clip)
            DispatchQueue.main.async { if let ready { self?.onNewClip?(ready) } }
        }
    }

    /// Turns copied picture data into PNG plus a small preview. Safe on a background thread.
    static func prepareImage(_ clip: NewClip) -> NewClip? {
        guard let raw = clip.png, let rep = NSBitmapImageRep(data: raw),
              let png = rep.representation(using: .png, properties: [:]) else { return nil }
        var out = clip
        out.png = png
        out.width = rep.pixelsWide
        out.height = rep.pixelsHigh
        out.thumb = Store.makeThumb(png)
        return out
    }

    static func read(_ pb: NSPasteboard, types: Set<String>) -> NewClip? {
        // Files from Finder.
        if types.contains(NSPasteboard.PasteboardType.fileURL.rawValue),
           let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            return NewClip(kind: .file, text: urls.map(\.path).joined(separator: "\n"))
        }
        let string = pb.string(forType: .string)
        let hasText = !(string?.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty ?? true)
        // Images (only when there is no real text alongside, e.g. a copied photo or screenshot).
        if !hasText, let data = pb.data(forType: .png) ?? pb.data(forType: .tiff), data.count <= maxImageBytes {
            return NewClip(kind: .image, text: "", png: data)   // converted by prepareImage
        }
        guard hasText, var text = string else { return nil }
        if text.utf8.count > maxTextBytes { text = String(text.prefix(maxTextBytes / 4)) }
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        if ColorText.isColor(trimmed) { return NewClip(kind: .color, text: trimmed) }
        if LinkCleaner.isLink(trimmed) { return NewClip(kind: .link, text: trimmed) }
        var html = pb.string(forType: .html)
        if (html?.utf8.count ?? 0) > 300_000 { html = nil }
        return NewClip(kind: .text, text: text, html: html)
    }
}

enum PasteStyle { case normal, plain, markdown }

enum Paster {
    /// Puts the item on the clipboard in the chosen style. Returns false if nothing could be written.
    @discardableResult
    static func copy(_ item: ClipItem, style: PasteStyle, to pb: NSPasteboard = .general) -> Bool {
        // Read the image before touching the clipboard, so a missing file never wipes it.
        var imageData: Data?
        if item.kind == .image {
            guard let name = item.image, let data = try? Data(contentsOf: Store.shared.imageURL(name)) else { return false }
            imageData = data
        }
        pb.clearContents()
        var ok = false
        switch (item.kind, style) {
        case (.image, _):
            if let data = imageData {
                ok = pb.setData(data, forType: .png)
                if let tiff = NSImage(data: data)?.tiffRepresentation { pb.setData(tiff, forType: .tiff) }
            }
        case (.file, .normal):
            let urls = item.text.split(separator: "\n").map { URL(fileURLWithPath: String($0)) as NSURL }
            ok = pb.writeObjects(urls)
        case (_, .markdown):
            ok = pb.setString(Markdown.from(item), forType: .string)
        case (.link, .normal):
            ok = pb.setString(item.text, forType: .string)
            pb.setString(item.text, forType: .URL)
        case (.text, .normal):
            ok = pb.setString(item.text, forType: .string)
            if let html = item.html { pb.setString(html, forType: .html) }
        default:
            ok = pb.setString(item.text, forType: .string)
        }
        pb.setData(Data(), forType: tenaxMarker)
        return ok
    }

    static var canPasteDirectly: Bool { AXIsProcessTrusted() }

    /// Shows the system "allow Memo to control your computer" request (Solomon clicks Allow).
    static func askForPermission() {
        let key = kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String
        _ = AXIsProcessTrustedWithOptions([key: true] as CFDictionary)
    }

    /// Presses Command-V in the app in front.
    static func pressPaste() {
        guard canPasteDirectly else { return }
        let src = CGEventSource(stateID: .combinedSessionState)
        let vKey: CGKeyCode = 9
        let down = CGEvent(keyboardEventSource: src, virtualKey: vKey, keyDown: true)
        let up = CGEvent(keyboardEventSource: src, virtualKey: vKey, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cgSessionEventTap)
        up?.post(tap: .cgSessionEventTap)
    }
}

enum LinkCleaner {
    static let exact: Set<String> = [
        "fbclid", "gclid", "dclid", "gbraid", "wbraid", "msclkid", "yclid", "twclid", "ttclid",
        "igshid", "igsh", "mc_cid", "mc_eid", "_hsenc", "_hsmi", "mkt_tok", "ref_src", "li_fat_id",
        "s_cid", "oly_enc_id", "oly_anon_id", "vero_id", "vero_conv", "__s", "rb_clickid", "_ga", "_gl",
        "ncid", "srsltid", "epik", "sc_cid", "wt_mc", "wickedid", "trk", "trkcampaign",
    ]
    /// Hosts where "si" and "feature" are share trackers rather than real settings.
    static let shareHosts = ["youtube.com", "youtu.be", "spotify.com", "music.apple.com"]

    static func isLink(_ s: String) -> Bool {
        guard !s.contains(where: \.isWhitespace), let url = URL(string: s),
              let scheme = url.scheme?.lowercased(), ["http", "https"].contains(scheme), url.host != nil else { return false }
        return true
    }

    /// The link without tracking parameters, or nil if it is not a web link.
    static func clean(_ s: String) -> String? {
        guard isLink(s), var comps = URLComponents(string: s) else { return nil }
        let host = comps.host?.lowercased() ?? ""
        let shareHost = shareHosts.contains { host == $0 || host.hasSuffix("." + $0) }
        if let items = comps.queryItems {
            let kept = items.filter { q in
                let n = q.name.lowercased()
                if n.hasPrefix("utm_") || exact.contains(n) { return false }
                if shareHost, n == "si" || n == "feature" { return false }
                return true
            }
            comps.queryItems = kept.isEmpty ? nil : kept
        }
        return comps.string ?? s
    }
}

enum ColorText {
    static func isColor(_ s: String) -> Bool { nsColor(s) != nil }

    static func nsColor(_ s: String) -> NSColor? {
        var hex = s.lowercased()
        guard hex.hasPrefix("#") else { return rgb(hex) }
        hex.removeFirst()
        guard [3, 6, 8].contains(hex.count), hex.allSatisfy(\.isHexDigit), let v = UInt64(hex, radix: 16) else { return nil }
        if hex.count == 3 {
            let r = (v >> 8) & 0xF, g = (v >> 4) & 0xF, b = v & 0xF
            return NSColor(srgbRed: CGFloat(r * 17) / 255, green: CGFloat(g * 17) / 255, blue: CGFloat(b * 17) / 255, alpha: 1)
        }
        let rgbv = hex.count == 8 ? v >> 8 : v
        let a = hex.count == 8 ? CGFloat(v & 0xFF) / 255 : 1
        return NSColor(srgbRed: CGFloat((rgbv >> 16) & 0xFF) / 255, green: CGFloat((rgbv >> 8) & 0xFF) / 255,
                       blue: CGFloat(rgbv & 0xFF) / 255, alpha: a)
    }

    /// rgb(1, 2, 3) or rgba(1, 2, 3, 0.5)
    private static func rgb(_ s: String) -> NSColor? {
        guard s.hasPrefix("rgb"), s.hasSuffix(")"), let open = s.firstIndex(of: "(") else { return nil }
        let parts = s[s.index(after: open)..<s.index(before: s.endIndex)].split(separator: ",")
            .map { $0.trimmingCharacters(in: .whitespaces) }
        guard parts.count == 3 || parts.count == 4 else { return nil }
        let nums = parts.compactMap(Double.init)
        guard nums.count == parts.count, nums.prefix(3).allSatisfy({ (0...255).contains($0) }) else { return nil }
        return NSColor(srgbRed: nums[0] / 255, green: nums[1] / 255, blue: nums[2] / 255, alpha: nums.count == 4 ? nums[3] : 1)
    }
}

enum Markdown {
    static func from(_ item: ClipItem) -> String {
        switch item.kind {
        case .link:
            let title = URL(string: item.text).flatMap { u in u.host.map { $0 + (u.path == "/" ? "" : u.path) } } ?? item.text
            return "[\(title)](\(item.text))"
        case .file:
            return item.text.split(separator: "\n").map { p in
                let url = URL(fileURLWithPath: String(p))
                return "[\(url.lastPathComponent)](\(url.absoluteString))"
            }.joined(separator: "\n")
        case .text:
            if let html = item.html, let md = fromHTML(html), !md.isEmpty { return md }
            return item.text
        default:
            return item.text
        }
    }

    /// Rich text to Markdown: bold, italic, links and line breaks.
    static func fromHTML(_ html: String) -> String? {
        // Remove anything that could make the HTML reader load from the internet.
        var safe = html
        for pattern in ["(?is)<(script|style|iframe|object|embed|video|audio)[^>]*>.*?</\\1>",
                        "(?is)<(img|link|meta|source|iframe|embed|base)[^>]*>", "(?i)url\\([^)]*\\)",
                        "(?i)\\s(src|srcset|background|poster)\\s*=\\s*(\"[^\"]*\"|'[^']*'|[^\\s>]+)"] {
            safe = safe.replacingOccurrences(of: pattern, with: "", options: .regularExpression)
        }
        guard let data = safe.data(using: .utf8),
              let attr = try? NSAttributedString(data: data, options: [.documentType: NSAttributedString.DocumentType.html,
                                                                       .characterEncoding: String.Encoding.utf8.rawValue],
                                                 documentAttributes: nil) else { return nil }
        var out = ""
        attr.enumerateAttributes(in: NSRange(location: 0, length: attr.length)) { attrs, range, _ in
            let raw = (attr.string as NSString).substring(with: range)
            // Keep surrounding spaces and line breaks outside the markers.
            let core = raw.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !core.isEmpty else { out += raw; return }
            let lead = String(raw.prefix(while: { $0.isWhitespace || $0.isNewline }))
            let trail = String(raw.reversed().prefix(while: { $0.isWhitespace || $0.isNewline }).reversed())
            var piece = core
            let traits = (attrs[.font] as? NSFont)?.fontDescriptor.symbolicTraits ?? []
            if traits.contains(.italic) { piece = "*\(piece)*" }
            if traits.contains(.bold) { piece = "**\(piece)**" }
            if let link = attrs[.link] {
                let target = (link as? URL)?.absoluteString ?? (link as? String) ?? ""
                if !target.isEmpty { piece = "[\(piece)](\(target))" }
            }
            out += lead + piece + trail
        }
        return out.trimmingCharacters(in: .whitespacesAndNewlines)
    }
}

/// Fast fuzzy match: whole-word and substring hits rank first, then letters in order.
enum Fuzzy {
    static func score(_ query: String, in text: String) -> Int? {
        let q = query.lowercased()
        guard !q.isEmpty else { return 0 }
        let t = String(text.prefix(4000)).lowercased()
        if let r = t.range(of: q) {
            let pos = t.distance(from: t.startIndex, to: r.lowerBound)
            return 10_000 - min(pos, 5_000) + (pos == 0 ? 2_000 : 0)
        }
        // Letters in order, close together (no matching letters scattered across a long text).
        let qs = Array(q.filter { !$0.isWhitespace }), ts = Array(t.prefix(600))
        guard let firstChar = qs.first else { return 0 }
        let maxSpan = qs.count * 3 + 2
        var best: Int?
        for start in ts.indices where ts[start] == firstChar {
            var ti = start + 1, gaps = 0, streak = 0, score = 0, ok = true
            for qc in qs.dropFirst() {
                var j = ti
                while j < ts.count, ts[j] != qc, j - start < maxSpan { j += 1 }
                guard j < ts.count, ts[j] == qc, j - start < maxSpan else { ok = false; break }
                streak = (j == ti) ? streak + 1 : 0
                gaps += j - ti
                score += 10 + streak * 8
                ti = j + 1
            }
            guard ok else { continue }
            let wordStart = start == 0 || !ts[start - 1].isLetter
            let total = score - gaps * 3 + (wordStart ? 15 : 0) - min(start, 200) / 20
            best = max(best ?? Int.min, total)
        }
        return best
    }
}
